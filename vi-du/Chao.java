public class Chao { // dòng 2
    public static void main(String[] args) { // dòng 3
        var a = 5; // dòng 4
        var b = 2; // dòng 5
        while (a > b) { // dòng 7
            System.out.println("a = " + a); // dòng 8
            a = a - 1; // dòng 9
        }
        if (a == b) { // dòng 12
            System.out.println("Khi nào xong? Xong rồi!"); // dòng 13
        } else {
            System.out.println("chưa xong"); // dòng 15
        }
    }
}
